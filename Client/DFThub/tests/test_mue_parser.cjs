const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const Module = require('node:module');
const ts = require('typescript');
const filename = path.resolve(__dirname, '../src/replica/mue.ts');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, esModuleInterop: true } });
const implementation = new Module(filename);
implementation.filename = filename;
implementation.paths = Module._nodeModulePaths(path.dirname(filename));
implementation._compile(compiled.outputText, filename);
const { parseDatasetMue, originalMueForRun } = implementation.exports;
const native = JSON.parse(fs.readFileSync(path.join(path.dirname(filename), 'cf22d-native.json'), 'utf8'));
assert.equal(native.coefficients.length, 59);
assert.equal(native.coefficients[0], 0.244161160);
assert.equal(native.coefficients[58], 0.462806);
assert.ok(Object.keys(native.datasets).length >= 91);
assert.equal(Object.keys(native.datasets).some(key => key.toLowerCase() === 'input'), false);
const meta = { source: 'libxc-native-cf22d', parameter_sha256: native.parameter_sha256 };
const baseline = originalMueForRun('input\t1.4192\nAE17\t373.9165', meta);
assert.equal(baseline.get('input'), 1.4192);
assert.equal(baseline.get('ae17'), native.datasets.AE17);
assert.ok(Math.abs(baseline.get('ae17') - 7.073824293895678) < 1e-7);
assert.equal(originalMueForRun('input\t4.25', null).has('input'), false);
assert.equal(originalMueForRun('input\t4.25', { ...meta, parameter_sha256: 'old' }).has('input'), false);
assert.equal(originalMueForRun('input\t0', meta).get('input'), 0);
assert.equal(originalMueForRun('input\t10.95', meta).get('input'), 10.95);
const rows = parseDatasetMue('------------SUMMARY-------------\nBH76RC\t1.05\ninput\t0\nZero\t0\nnew_total_mue:1.90\n------------LOSS----------------\nWeighted MUE sum:\t527.95\nRegularization (0.01*(a+b+c)):\t14.29\nTotal loss:\t542.24');
assert.deepEqual(rows.map(row => row.name), ['Input', 'BH76RC', 'Zero']);
assert.equal(rows[0].value, 0);
assert.deepEqual(parseDatasetMue('Weighted MUE sum:\t99\nRegularization (0.01*(a+b+c)):\t88\nTotal loss:\t77'), []);
assert.equal(parseDatasetMue('Database\tMUE\nINPUT_ref\t1.2e-3')[0].key, 'input');
assert.deepEqual(parseDatasetMue('NaNSet\tNaN\nInfSet\tInfinity\nNegSet\t-1'), []);
console.log('PASS MUE parsing: datasets only, Input first, loss exclusions, zero values and reference matching');
